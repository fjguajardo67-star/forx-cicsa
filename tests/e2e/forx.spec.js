import { test, expect } from '@playwright/test';
import { purchaseXml } from '../fixtures/monthly.js';

async function validateIngredient(page,{name,sku,uuid,price='360'}) {
  await page.getByRole('button',{name:'Importar XML',exact:true}).first().click();
  await page.getByLabel('Periodo del lote').fill('2026-09');
  const xml=purchaseXml({uuid,concepts:[{description:name+' CAJA 12 KG',sku,quantity:'1',unit:'XBX',unitPrice:price,amount:price}]});
  await page.locator('#xml-files').setInputFiles({name:`${sku}.xml`,mimeType:'application/xml',buffer:Buffer.from(xml)});
  await page.getByRole('button',{name:'Ir a la cola de revisión'}).click();
  await page.locator('[data-review-row]').filter({hasText:name+' CAJA 12 KG'}).click();
  await page.getByRole('button',{name:'Editar producto',exact:true}).click();
  await page.getByLabel('Presentación',{exact:true}).fill('Caja');
  await page.getByLabel('Contenido por presentación').fill('12');
  await page.getByRole('combobox',{name:'Unidad de contenido',exact:true}).selectOption('kg');
  await page.getByRole('combobox',{name:'Categoría',exact:true}).selectOption('cat_frutas');
  await page.getByRole('button',{name:'Guardar producto',exact:true}).click();
  await page.getByRole('button',{name:'Crear ingrediente',exact:true}).click();
  await page.getByLabel('Nombre del ingrediente').fill(name);
  await page.getByLabel('Merma (%)',{exact:true}).fill('0');
  await page.getByLabel('Merma confirmada el').fill('2026-01-01');
  await page.getByRole('button',{name:'Crear y vincular',exact:true}).click();
  await page.getByRole('button',{name:'Validar precio real',exact:true}).click();
  await expect(page.locator('[data-review-row]').filter({hasText:name+' CAJA 12 KG'})).toContainText('Validado');
}
async function createRecipe(page,name,type,missing=false){
  await page.getByRole('button',{name:'Agregar receta',exact:true}).click();
  await page.getByRole('button',{name:'Capturar receta manualmente'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nombre',{exact:true}).fill(name);
  await dialog.getByLabel('Tipo',{exact:true}).selectOption(type);
  await dialog.getByRole('button',{name:'Agregar ingrediente',exact:true}).click();
  await dialog.getByLabel('Nombre ingrediente 1',{exact:true}).fill('Jitomate');
  await dialog.getByLabel('Cantidad ingrediente 1',{exact:true}).fill('100');
  await dialog.getByLabel('Vincular ingrediente 1',{exact:true}).selectOption({label:'Jitomate · kg'});
  if(missing){
    await dialog.getByRole('button',{name:'Agregar ingrediente',exact:true}).click();
    await dialog.getByLabel('Nombre ingrediente 2',{exact:true}).fill('Aguacate');
    await dialog.getByLabel('Cantidad ingrediente 2',{exact:true}).fill('50');
  }
  await dialog.getByLabel('Procedimiento').fill('Preparar y servir.');
  await dialog.getByRole('button',{name:'Guardar receta',exact:true}).click();
  await expect(dialog).not.toBeVisible();
}
